// TRIM: trailing blanks only.
std::string_view ftrim(const char* s, int len) {
    int n = len;
    while (n > 0 && s[n - 1] == ' ') --n;
    return std::string_view(s, static_cast<size_t>(n));
}

// A Fortran CHARACTER assignment blank-fills the ENTIRE declared width and
// truncates what does not fit. Both halves matter here.
void fassign(char* dst, int width, std::string_view src) {
    const int n = static_cast<int>(src.size()) < width
                      ? static_cast<int>(src.size()) : width;
    if (n > 0) std::memcpy(dst, src.data(), static_cast<size_t>(n));
    if (n < width) std::memset(dst + n, ' ', static_cast<size_t>(width - n));
}

