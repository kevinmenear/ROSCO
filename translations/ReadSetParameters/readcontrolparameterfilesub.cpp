// --- The ALLOCATABLE array dummies of ParseDbAry_Opt / ParseInAry_Opt -------
//
// Both callees take `REAL(8)/INTEGER, INTENT(INOUT), ALLOCATABLE :: Ary(:)`,
// which crosses BIND(C) as a CFI descriptor, and both ALLOCATE INTO IT
// (`CFI_allocate`, parsedbary_opt.cpp:587). The view carries the same field as
// a bare pointer + size, so the descriptor has to be built here and read back
